def plural_days(n: int) -> str:
    n_abs = abs(n)
    if n_abs % 10 == 1 and n_abs % 100 != 11:
        return f"{n} день"
    if 2 <= n_abs % 10 <= 4 and not 12 <= n_abs % 100 <= 14:
        return f"{n} дня"
    return f"{n} дней"


